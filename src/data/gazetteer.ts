function key(s: string) {
  return s.trim().toLowerCase().replace(/[.,]/g, " ").replace(/\s+/g, " ");
}

export function lookupGazetteer(...parts: Array<string | undefined>): (LatLng & { label: string }) | null {
  const tokens = parts.filter(Boolean).map((p) => key(String(p)));
  for (const token of tokens) {
    if (GAZETTEER[token]) return { ...GAZETTEER[token], label: token };
    const bits = token.split(" ").filter(Boolean);
    for (let n = bits.length; n >= 1; n--) {
      for (let i = 0; i + n <= bits.length; i++) {
        const slice = bits.slice(i, i + n).join(" ");
        if (GAZETTEER[slice]) return { ...GAZETTEER[slice], label: slice };
      }
    }
  }
  return null;
}
